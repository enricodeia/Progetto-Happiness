// Full media list — poster image + looping video per case + editorial copy.
export function metalabMedia() {
  return CASES.map(([folder, poster, video, tag, paragraph]) => ({
    image: enc(`Projects/${folder}/${poster}`),
    video: enc(`Projects/${folder}/${video}`),
    title: folder,
    tag,
    paragraph,
    year: "2026",
  }));
}

// Back-compat: posters only (used by image-only components like OnScroll).
export function metalabImages() {
  return metalabMedia().map((m) => ({ ...m, url: m.image }));
}
